#!/usr/bin/env bash
set -euo pipefail

# Package one forced-alignment acoustic model into zh-<name>.tar.bz2 for the
# fa-models GitHub release (the language prefix keeps the names unambiguous
# once models for other languages are added). The archive contains a single
# model directory with only the files required by sherpa-onnx-fa, plus
# lexicon.txt and a README.md documenting where the model comes from:
#
#   zh-<name>/meta.json      feature chain + silence/OOV parameters
#   zh-<name>/final.alimdl   alignment model (kaldi TransitionModel + AmDiagGmm)
#   zh-<name>/tree           context dependency tree
#   zh-<name>/lda.mat        LDA transform of the feature chain
#   zh-<name>/phones.txt     phone table
#   zh-<name>/lexicon.txt    pronunciation dictionary (generated)
#   zh-<name>/README.md      model provenance (written here)
#
# Extra files of the upstream release bundle (final.mdl, phone_lm.fst,
# graphemes.txt, phone_pdf.counts, the pronunciation dictionaries and the
# nested zip files) are NOT included.
#
# Usage: package-fa-model.sh <aishell3_pinyin|biaobei_pinyin|large_pinyin>

if [ $# -ne 1 ]; then
  echo "usage: $0 <aishell3_pinyin|biaobei_pinyin|large_pinyin>"
  exit 1
fi

name=$1
case $name in
  aishell3_pinyin|biaobei_pinyin|large_pinyin) ;;
  *)
    echo "error: unknown model: $name"
    exit 1
    ;;
esac
pkg=zh-${name//_/-}

script_dir=$(cd "$(dirname "$0")" && pwd)
cd "$script_dir/$name"

# 1. download the model and generate lexicon.txt (no-op when already done)
./run.sh

# 2. locate the extracted acoustic model directory (contains meta.json)
meta=$(find download -name meta.json -type f | head -1)
if [ -z "$meta" ]; then
  echo "error: no extracted model (meta.json) under $name/download"
  exit 1
fi
model_dir=$(dirname "$meta")

# 3. stage the model directory with the required files only
stage=fa-model/$pkg
rm -rf fa-model
mkdir -p "$stage"
for f in meta.json final.alimdl tree lda.mat phones.txt; do
  cp "$model_dir/$f" "$stage/"
done
cp lexicon.txt "$stage/"

# test wav shipped with the package (transcript in the usage example below)
wav=download/zh.wav
if [ ! -f "$wav" ]; then
  echo "Downloading zh.wav"
  curl -SL --fail --retry 5 --retry-all-errors --connect-timeout 30 \
    -o "$wav.tmp" https://github.com/k2-fsa/sherpa-onnx/releases/download/asr-models/zh.wav
  mv "$wav.tmp" "$wav"
fi
cp "$wav" "$stage/"

cat > "$stage/README.md" <<EOF
# $pkg - forced-alignment acoustic model

This is the $pkg acoustic model for forced alignment, as used by
sherpa-onnx-fa of https://github.com/k2-fsa/sherpa-onnx. The "zh-" prefix
marks the language (Chinese); models for other languages follow the same
<language>-<name> scheme.

## Where the model comes from

- Model archive: https://github.com/lars76/forced-alignment-chinese/releases/download/model_files/${name}.zip
  (upstream name: $name)
- Source repository: https://github.com/lars76/forced-alignment-chinese
  (the model is a GMM-HMM acoustic model trained with the Montreal Forced
  Aligner - see the upstream README for training details)

This directory is a re-packaging made by
scripts/mfa/zh/lars76/package-fa-model.sh of
https://github.com/k2-fsa/sherpa-onnx: only the files required for forced
alignment are kept (the extra files of the upstream bundle, e.g. final.mdl,
phone_lm.fst, graphemes.txt, phone_pdf.counts and the pronunciation
dictionaries, are dropped).

## Files

- meta.json      feature chain + silence/OOV parameters
- final.alimdl   alignment model (kaldi TransitionModel + AmDiagGmm)
- tree           context dependency tree
- lda.mat        LDA transform of the feature chain
- phones.txt     phone table
- lexicon.txt    pronunciation dictionary (hanzi/phrase -> phones; " || "
                 groups the phones per character), generated by
                 scripts/mfa/zh/lars76/$name/generate_lexicon.py of
                 https://github.com/k2-fsa/sherpa-onnx
- zh.wav         test wav (its transcript is the --text below)

## License

This model follows whatever license the original model uses; see the
[source repository](https://github.com/lars76/forced-alignment-chinese) for
the license terms.

## Usage

The test wav zh.wav is included so the package works out of the box.
sherpa-onnx-fa is only a demo: the same model can be used through the
APIs of all languages supported by sherpa-onnx.

  sherpa-onnx-fa \\
    --model-dir=$pkg \\
    --lexicon=$pkg/lexicon.txt \\
    --wav=$pkg/zh.wav \\
    --text="不要问你的国家能为你做什么，而要问你能为你的国家做什么。" \\
    --out=output.TextGrid
EOF

# 4. create the tarball next to this script
ls -lh "$stage"

(cd fa-model && tar cjf "$script_dir/$pkg.tar.bz2" "$pkg")
rm -rf fa-model
echo "wrote $script_dir/$pkg.tar.bz2"
tar tjf "$script_dir/$pkg.tar.bz2"
